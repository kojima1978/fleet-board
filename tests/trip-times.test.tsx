import assert from "node:assert/strict";
import { renderToStaticMarkup } from "react-dom/server";
import { tripOverlaps, validateActualStart, validateReservationStart, type StartTimeRecord } from "../lib/trip-times";
import { ReservationTimeEditor } from "../components/reservation-time-editor";
import { ActualStartEditor } from "../components/trip-start-editors";

const now = new Date();
const at = (minutes: number) => new Date(now.getTime() + minutes * 60_000);
const used = { status: "IN_USE", actualStart: at(-60), actualEnd: null };
assert.doesNotThrow(() => validateReservationStart(at(30), at(45), now));
assert.throws(() => validateReservationStart(at(0), at(45), now));
assert.throws(() => validateReservationStart(at(30), at(44), now));
assert.throws(() => validateReservationStart(at(30), at(30 + 10_081), now));
assert.doesNotThrow(() => validateActualStart(used, at(-90), "操作を忘れたため", now));
assert.throws(() => validateActualStart(used, at(1), "訂正", now));
assert.throws(() => validateActualStart(used, at(-90), "  ", now));
assert.throws(() => validateActualStart(used, at(-90), "あ".repeat(201), now));
assert.throws(() => validateActualStart(used, at(-60), "訂正", now));
assert.throws(() => validateActualStart({ ...used, status: "RESERVED" }, at(-90), "訂正", now));
const completed = { ...used, status: "COMPLETED", actualEnd: at(-30) };
assert.doesNotThrow(() => validateActualStart(completed, at(-75), "訂正", now));
assert.throws(() => validateActualStart(completed, at(-30), "訂正", now));
assert.throws(() => validateActualStart(completed, at(-10), "訂正", now));
const interval = { ...completed, plannedStart: at(-65), plannedEnd: at(-25) };
assert.equal(tripOverlaps(interval, at(-90), at(-60)), false, "隣接する利用は重複ではない");
assert.equal(tripOverlaps(interval, at(-90), at(-59)), true);
assert.equal(tripOverlaps(interval, at(-30), at(-15)), false);
assert.equal(tripOverlaps({ ...interval, status: "IN_USE", actualEnd: null }, at(30), at(60)), true);
const record: StartTimeRecord = { id: "t1", version: 1, status: "IN_USE", plannedStart: at(-60).toISOString(), plannedEnd: at(60).toISOString(), actualStart: at(-60).toISOString(), actualEnd: null, vehicle: { name: "車両" }, employee: { name: "社員" } };
const noop = async () => true;
const html = renderToStaticMarkup(<ActualStartEditor trip={record} busy={false} actorAvailable={false} onSave={noop} />);
assert.match(html, /<details/);
assert.match(html, /その他：利用開始時刻を訂正/);
assert.match(html, /訂正理由/);
assert.match(html, /先にこの端末の利用者を選択/);
assert.match(html, /disabled=""/);
assert.equal(renderToStaticMarkup(<ActualStartEditor trip={{ ...record, status: "RESERVED" }} busy={false} actorAvailable onSave={noop} />), "");
assert.match(renderToStaticMarkup(<ReservationTimeEditor trip={{ plannedStart: at(30).toISOString(), plannedEnd: at(90).toISOString() }} busy={false} onSave={noop} />), /利用時間を維持/);
assert.match(renderToStaticMarkup(<ReservationTimeEditor trip={{ plannedStart: at(30).toISOString(), plannedEnd: at(90).toISOString() }} busy={false} onSave={noop} />), /disabled=""/, "元記録に秒・ミリ秒があっても未入力では変更できない");
console.log("Trip time tests passed: reservation/actual start limits, required reason, overlap boundaries, rare-action UI and operator selection");
